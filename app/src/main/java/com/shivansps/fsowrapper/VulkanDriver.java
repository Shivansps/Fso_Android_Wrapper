package com.shivansps.fsowrapper;

import android.content.Context;
import android.net.Uri;
import android.os.Build;

import org.json.JSONException;
import org.json.JSONObject;

import java.io.BufferedInputStream;
import java.io.DataInputStream;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.StandardOpenOption;
import java.util.UUID;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;

final class VulkanDriver {
    static final String EXTRA_ID = "fsoVulkanDriverId";

    private static final long MAX_PACKAGE_BYTES = 256L * 1024 * 1024;
    private static final int MAX_METADATA_BYTES = 64 * 1024;
    private static final int MAX_ENTRIES = 256;
    private static final String METADATA = "meta.json";
    private static final String LIBRARY_PATTERN = "[A-Za-z0-9_.+-]+\\.so";

    final File directory;
    final String name;
    private final String libraryName;

    private VulkanDriver(File directory, String name, String libraryName) {
        this.directory = directory;
        this.name = name;
        this.libraryName = libraryName;
    }

    static VulkanDriver importPackage(Context context, Uri uri) throws IOException {
        File directory = new File(root(context), UUID.randomUUID().toString());
        Files.createDirectory(directory.toPath());
        boolean imported = false;
        try {
            try (InputStream source = context.getContentResolver().openInputStream(uri)) {
                if (source == null) {
                    throw new IOException("Could not open the driver ZIP.");
                }
                extractPackage(source, directory);
            }
            VulkanDriver result = readPackage(directory);
            imported = true;
            return result;
        } finally {
            if (!imported) {
                File[] files = directory.listFiles();
                if (files != null) {
                    for (File file : files) {
                        file.delete();
                    }
                }
                directory.delete();
            }
        }
    }

    static VulkanDriver find(Context context, String id) throws IOException {
        try {
            if (id != null && id.equals(UUID.fromString(id).toString())) {
                return readPackage(new File(root(context), id));
            }
        } catch (IllegalArgumentException ignored) {
            // Only UUIDs generated by importPackage identify an installed driver.
        }
        throw new IOException("Invalid Vulkan driver package ID.");
    }

    boolean configure(Context context) throws IOException {
        System.loadLibrary("fsovulkan");
        File temp = null;
        if (Build.VERSION.SDK_INT == 28) {
            temp = Files.createTempDirectory(context.getCacheDir().toPath(), "fso-vulkan-").toFile();
        }
        return configureLoader(context.getApplicationInfo().nativeLibraryDir,
                temp == null ? null : temp.getAbsolutePath(), directory.getAbsolutePath(), libraryName);
    }

    private static File root(Context context) {
        return context.getDir("vulkan_drivers", Context.MODE_PRIVATE);
    }

    private static void extractPackage(InputStream source, File directory) throws IOException {
        byte[] buffer = new byte[64 * 1024];
        long total = 0;
        int entryCount = 0;
        try (ZipInputStream zip = new ZipInputStream(new BufferedInputStream(source))) {
            for (ZipEntry entry; (entry = zip.getNextEntry()) != null; zip.closeEntry()) {
                if (++entryCount > MAX_ENTRIES) {
                    throw new IOException("The driver ZIP has too many entries.");
                }

                String name = entry.getName();
                // ADPKG uses a flat package. Only recognized basenames can be written.
                boolean metadata = METADATA.equals(name);
                boolean extract = !entry.isDirectory() && (metadata || name.matches(LIBRARY_PATTERN));
                try (OutputStream output = extract ? Files.newOutputStream(
                        new File(directory, name).toPath(), StandardOpenOption.CREATE_NEW) : null) {
                    long entryBytes = 0;
                    for (int count; (count = zip.read(buffer)) != -1; ) {
                        total += count;
                        entryBytes += count;
                        if (total > MAX_PACKAGE_BYTES || (metadata && entryBytes > MAX_METADATA_BYTES)) {
                            throw new IOException("The driver ZIP exceeds the import size limit.");
                        }
                        if (output != null) {
                            output.write(buffer, 0, count);
                        }
                    }
                }
            }
        }
    }

    private static VulkanDriver readPackage(File directory) throws IOException {
        File metadata = new File(directory, METADATA);
        if (!metadata.isFile() || metadata.length() > MAX_METADATA_BYTES) {
            throw new IOException("Expected meta.json at the root of the driver ZIP.");
        }
        try {
            JSONObject json = new JSONObject(new String(Files.readAllBytes(metadata.toPath()), StandardCharsets.UTF_8));
            String libraryName = json.getString("libraryName");
            if (!libraryName.matches(LIBRARY_PATTERN)) {
                throw new IOException("Invalid driver libraryName in meta.json.");
            }
            int minApi = json.optInt("minApi", 28);
            if (minApi > Build.VERSION.SDK_INT) {
                throw new IOException("This driver needs Android API " + minApi + " or later.");
            }
            checkArm64Library(new File(directory, libraryName));
            return new VulkanDriver(directory, json.optString("name", libraryName), libraryName);
        } catch (JSONException exception) {
            throw new IOException("Invalid Vulkan driver metadata.", exception);
        }
    }

    private static void checkArm64Library(File library) throws IOException {
        byte[] elfHeader = new byte[20];
        try (DataInputStream input = new DataInputStream(Files.newInputStream(library.toPath()))) {
            input.readFully(elfHeader);
        }
        if (elfHeader[0] != 0x7f || elfHeader[1] != 'E' || elfHeader[2] != 'L' || elfHeader[3] != 'F'
                || elfHeader[4] != 2 || elfHeader[5] != 1
                || elfHeader[16] != 3 || elfHeader[17] != 0
                || Byte.toUnsignedInt(elfHeader[18]) != 183 || elfHeader[19] != 0) {
            throw new IOException("The main driver library must be an ARM64 shared object.");
        }
    }

    private static native boolean configureLoader(
            String nativeDir, String tempDir, String driverDir, String libraryName);
}
